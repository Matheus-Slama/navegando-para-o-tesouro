import assert from 'node:assert/strict';
import { webcrypto } from 'node:crypto';
import { HIGHSCORE_KEY, readHighscore, saveHighscore } from '../src/game/core/highscore.js';
import { calculateScore } from '../src/game/core/scoring.js';

const values = new Map();
const storage = { getItem: (key) => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) };
assert.equal(await readHighscore(storage, webcrypto), 0);
assert.equal(await saveHighscore(storage, 1250, webcrypto), true);
assert.equal(await readHighscore(storage, webcrypto), 1250);
await saveHighscore(storage, 500, webcrypto);
assert.equal(await readHighscore(storage, webcrypto), 1250);
await saveHighscore(storage, 3000, webcrypto);
assert.equal(await readHighscore(storage, webcrypto), 3000);
const record = JSON.parse(storage.getItem(HIGHSCORE_KEY));
const bytes = Buffer.from(record.data, 'base64');
bytes[0] ^= 1;
storage.setItem(HIGHSCORE_KEY, JSON.stringify({ ...record, data: bytes.toString('base64') }));
assert.equal(await readHighscore(storage, webcrypto), 0, 'Alteração do ciphertext deve ser rejeitada.');
storage.setItem(HIGHSCORE_KEY, '{broken');
assert.equal(await readHighscore(storage, webcrypto), 0);
assert.equal(await saveHighscore(storage, -1, webcrypto), false);
const blocked = { getItem() { throw Error('blocked'); }, setItem() { throw Error('blocked'); } };
assert.equal(await readHighscore(blocked, webcrypto), 0);
assert.equal(await saveHighscore(blocked, 100, webcrypto), false);
const phase = { score: { maxScore: 1250, targetTimeSeconds: 18 } };
assert.equal(calculateScore(phase, 5), 1250);
assert.equal(calculateScore(phase, 36), 625);
assert.equal(calculateScore(phase, -1), 0);
console.log('Pontuação, persistência criptografada, adulteração e armazenamento bloqueado: OK.');
